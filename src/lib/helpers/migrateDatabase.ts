/**
 * Executes a SQL migration file against the Supabase database
 * @param sqlFilePath Path to the SQL file to execute
 */
export const executeSqlMigration = async (sqlContent: string): Promise<void> => {
  try {
    console.log('Executing SQL migration...');
    const { error } = await supabase.rpc('exec_sql', { sql: sqlContent });
    
    if (error) {
      console.error('Migration error:', error);
      throw error;
    }
    
    console.log('Migration completed successfully');
  } catch (error) {
    console.error('Failed to execute migration:', error);
    throw error;
  }
};

/**
 * Checks if the replies table exists and creates it if it doesn't
 */
export const ensureForumRepliesTable = async (): Promise<void> => {
  try {
    // Check if table exists
    const { data, error } = await supabase
      .from('replies')
      .select('id')
      .limit(1);
    
    if (error && error.code === '42P01') { // Table doesn't exist
      console.log('replies table does not exist, creating it...');
      
      // Read the SQL file
      const sqlContent = `
      -- Create replies table if it doesn't exist
      CREATE TABLE IF NOT EXISTS replies (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        thread_id BIGINT NOT NULL,
        author_id UUID NOT NULL,
        content TEXT NOT NULL,
        date TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      
      -- Create index for faster queries
      CREATE INDEX IF NOT EXISTS replies_thread_id_idx ON replies(thread_id);
      CREATE INDEX IF NOT EXISTS replies_author_id_idx ON replies(author_id);
      
      -- Enable Row Level Security
      ALTER TABLE replies ENABLE ROW LEVEL SECURITY;
      
      -- Create policies
      CREATE POLICY "Anyone can view forum replies"
        ON replies
        FOR SELECT
        USING (true);
      
      CREATE POLICY "Authenticated users can insert their own replies"
        ON replies
        FOR INSERT
        WITH CHECK (auth.uid() = author_id);
      `;
      
      // Execute the SQL
      await executeSqlMigration(sqlContent);
      console.log('replies table created successfully');
    } else {
      console.log('replies table already exists');
    }
  } catch (error) {
    console.error('Error ensuring replies table:', error);
  }
};
